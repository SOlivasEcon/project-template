"""Turn a fresh copy of the template into your project. Run it once, right after "Use this template":

    pixi run python scripts/new_project.py

It asks for the project title, the package name and the author (or takes --title, --package, --author), then
  - renames the folder project_package/ to your package name and updates every reference to it;
  - puts the title and author in pyproject.toml, paper/main.tex, paper/slides/slides.tex, README.md and LICENSE
    (your copyright line is added above the template's, which the MIT license asks you to keep);
  - points the PyCharm run configurations (.run/) at this folder's name.
Then run `pixi install` (it updates pixi.lock for the new package name), check `git diff` and commit.
Afterwards this script is no longer needed; you may delete it.

Uses only the Python standard library, so any Python 3.10+ can run it.
"""

import argparse
import datetime
import keyword
import re
import subprocess
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
OLD_PACKAGE = "project_package"
TEMPLATE_DESCRIPTION = "Research project built from SOlivasEcon/project-template"
SKIP = {"pixi.lock", "scripts/new_project.py"}  # pixi.lock is regenerated by `pixi install`


def tracked_text_files() -> list[Path]:
    """Files tracked by git (or, without git, every file outside hidden and output folders) that are text."""
    try:
        listing = subprocess.run(["git", "ls-files"], cwd=REPO, capture_output=True, text=True, check=True).stdout
        names = listing.splitlines()
    except (OSError, subprocess.CalledProcessError):
        names = [p.relative_to(REPO).as_posix() for p in REPO.rglob("*")
                 if p.is_file() and not any(part.startswith((".pixi", ".git")) for part in p.parts)]
    files = []
    for name in names:
        path = REPO / name
        if name in SKIP or not path.is_file():
            continue
        try:
            path.read_text(encoding="utf-8")
        except UnicodeDecodeError:
            continue  # binary
        files.append(path)
    return files


def replace_in_file(path: Path, replacements: list[tuple[str, str]]) -> bool:
    """Apply (old, new) replacements to a file; return True if it changed. Keeps its line endings."""
    text = path.read_bytes().decode("utf-8")
    new = text
    for old, replacement in replacements:
        new = new.replace(old, replacement)
    if new != text:
        path.write_bytes(new.encode("utf-8"))
    return new != text


def ask(prompt: str, default: str) -> str:
    """Ask a question in the terminal; an empty answer keeps the default."""
    answer = input(f"{prompt} [{default}]: ").strip()
    return answer or default


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--title", help="project title, e.g. 'Inventories and Tariffs'")
    parser.add_argument("--package", help="Python package name: lowercase letters, digits and _, e.g. inventory_shocks")
    parser.add_argument("--author", help="author name(s) for the paper and the license")
    args = parser.parse_args()

    if not (REPO / OLD_PACKAGE).is_dir():
        raise SystemExit(f"{OLD_PACKAGE}/ not found: this project was already set up.")

    default_package = re.sub(r"\W", "_", REPO.name.lower().replace("-", "_"))
    title = args.title or ask("Project title", REPO.name)
    package = args.package or ask("Package name", default_package)
    author = args.author or ask("Author", "Author Name")
    if not re.fullmatch(r"[a-z][a-z0-9_]*", package) or keyword.iskeyword(package):
        raise SystemExit(f"'{package}' is not a valid package name: use lowercase letters, digits and _.")

    year = datetime.date.today().year
    changed = []
    for path in tracked_text_files():
        relative = path.relative_to(REPO).as_posix()
        replacements = [(OLD_PACKAGE, package), (OLD_PACKAGE.replace("_", "-"), package.replace("_", "-"))]
        if relative == "pyproject.toml":
            replacements.append((TEMPLATE_DESCRIPTION, title))
        elif relative in {"paper/main.tex", "paper/slides/slides.tex"}:
            replacements += [("{Project Title}", "{" + title + "}"), ("{Author Name}", "{" + author + "}")]
        elif relative == "LICENSE":
            replacements.append(("Copyright (c) ", f"Copyright (c) {year} {author}\nCopyright (c) "))
        elif relative.startswith(".run/"):
            replacements.append(('<module name="project-template" />', f'<module name="{REPO.name}" />'))
        elif relative == "README.md":
            text = path.read_text(encoding="utf-8")
            first_heading = re.search(r"^# .*$", text, re.MULTILINE)
            if first_heading:
                replacements.append((first_heading.group(0), f"# {title}"))
        if replace_in_file(path, replacements):
            changed.append(relative)

    (REPO / OLD_PACKAGE).rename(REPO / package)
    print(f"Renamed {OLD_PACKAGE}/ to {package}/ and updated {len(changed)} files:")
    print("\n".join(f"  {name}" for name in changed))
    print("\nNext: run `pixi install` (updates pixi.lock), check `git diff`, then commit.")


if __name__ == "__main__":
    main()
